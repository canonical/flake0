import importlib.util
import json
import os
import subprocess
import sys
from pathlib import Path

_SCRIPT_PATH = (
    Path(__file__).resolve().parent.parent
    / ".github"
    / "actions"
    / "summarize"
    / "scripts"
    / "summarize.py"
)
_spec = importlib.util.spec_from_file_location("summarize", _SCRIPT_PATH)
summarize = importlib.util.module_from_spec(_spec)
sys.modules["summarize"] = summarize
_spec.loader.exec_module(summarize)

RUN_URL = "https://github.com/o/r/actions/runs/1/attempts/1"
MARKER = "<!-- flake0-summary run=1 attempt=1 -->"


def _verdicts(tmp_path, *verdicts):
    for i, v in enumerate(verdicts):
        d = tmp_path / "verdicts" / f"flake0-verdict-leg{i}-1"
        d.mkdir(parents=True)
        (d / "verdict.json").write_text(json.dumps(v))
    return tmp_path / "verdicts"


def _run(tmp_path, *extra):
    out = tmp_path / "body.md"
    rc = summarize.main(["--verdicts", str(tmp_path / "verdicts"), "--run-url", RUN_URL,
                         "--marker", MARKER, "--out", str(out), *extra])
    return rc, out.read_text() if out.exists() else ""


AMD = {"job": "k8s/test_ha.py | amd64", "verdict": "FLAKY", "root_cause": "external_service",
       "failed_tests": ["test_build_and_deploy"], "summary": "Charmhub EOF."}
ARM = {"job": "k8s/test_ha.py | arm64", "verdict": "FLAKY", "root_cause": "environment_infra",
       "failed_tests": ["test_build_and_deploy"], "summary": "Build race."}
TLS = {"job": "k8s/test_tls.py | amd64", "verdict": "REAL_FAILURE", "root_cause": "test_defect",
       "summary": "Same-second certs.", "suggested_fix": "Compare with >=."}


def test_update_lists_each_job_by_bucket_worst_first(tmp_path):
    _verdicts(tmp_path, AMD, TLS, {"job": "k8s/test_x.py | amd64", "error": "classify left no verdict"})
    (tmp_path / "verdicts" / "broken").mkdir()
    (tmp_path / "verdicts" / "broken" / "verdict.json").write_text("{not json")
    rc, body = _run(tmp_path)
    assert rc == 0
    assert body.startswith(MARKER + "\n")
    assert f"Integration tests failing due to a mix of test issues and flakiness. [Full details on the run page]({RUN_URL})" in body
    assert "AI-generated by flake0" in body
    assert "Run in progress: 3 failed job(s) so far" in body
    assert body.index("### Test issues (1)") < body.index("### Flaky (1)") < body.index("### No verdict (1)")
    assert ("- `k8s/test_tls.py | amd64`: Same-second certs. Recommendation: fix test. Suggested fix: Compare with &gt;=."
            in body)
    assert "- `k8s/test_ha.py | amd64`, `test_build_and_deploy`: Charmhub EOF. Recommendation: retry safe." in body
    assert "- `k8s/test_x.py | amd64`: no classify verdict. Recommendation: needs human review." in body


def test_update_with_no_verdicts_posts_nothing(tmp_path):
    (tmp_path / "verdicts").mkdir()
    assert _run(tmp_path) == (1, "")


def test_final_groups_jobs_and_may_overrule(tmp_path, monkeypatch):
    _verdicts(tmp_path, AMD, ARM, TLS)
    seen = {}

    def fake_call(prompt, model, key, system):
        seen.update(prompt=prompt, system=system)
        return json.dumps({"groups": [
            {"test_file": "test_ha.py", "jobs": [AMD["job"], ARM["job"], "spoofed | job"],
             "failed_tests": ["test_build_and_deploy"], "verdict": "REAL_FAILURE", "root_cause": "test_defect",
             "summary": "Same empty charm URL on both arches.", "suggested_fix": "Build the charm first."},
            # a job the reply already used, and a non-dict, are ignored
            {"test_file": "dup.py", "jobs": [AMD["job"]], "verdict": "FLAKY", "root_cause": "environment_infra"},
            "junk",
        ]})

    monkeypatch.setattr(summarize.classify, "call_openrouter", fake_call)
    monkeypatch.setenv("OPENROUTER_API_KEY", "k")
    diff = tmp_path / "diff.patch"
    diff.write_text("+ change")
    rc, body = _run(tmp_path, "--final", "--model", "m", "--diff", str(diff))
    assert rc == 0
    assert "Same empty charm URL" not in seen["system"]
    assert "+ change" in seen["prompt"] and "Charmhub EOF." in seen["prompt"]
    assert "Run in progress" not in body
    assert "Integration tests failing due to test issues." in body
    assert "### Test issues (2)" in body
    assert ("- `test_ha.py` (k8s/test_ha.py | amd64, k8s/test_ha.py | arm64), `test_build_and_deploy`: "
            "Same empty charm URL on both arches. Recommendation: fix test. Suggested fix: Build the charm first.") in body
    # left out of the reply: keeps its own verdict
    assert "- `k8s/test_tls.py | amd64`: Same-second certs." in body
    assert "spoofed" not in body and "dup.py" not in body


