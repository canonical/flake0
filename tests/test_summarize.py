def test_model_text_cannot_inject_markup(tmp_path):
    hostile = {"job": "j`<!-- x -->", "verdict": "REAL_FAILURE", "root_cause": "code_regression",
               "failed_tests": ["test_x[a-b]"],
               "summary": "ping @team\n### Fake <img src=x> [approve](https://evil.example) ![t](p.png) o/r#1 www.evil.example &commat;team",
               "suggested_fix": "x" * 1000}
    _verdicts(tmp_path, hostile)
    _, body = _run(tmp_path)
    assert "Integration tests failing due to charm bugs." in body
    # code spans render nothing, so only the backtick changes
    assert "- `j'<!-- x -->`, `test_x[a-b]`: " in body
    assert "@team" not in body and "@\u200bteam" in body
    assert "&amp;commat;team" in body
    assert "<img" not in body and "&lt;img" in body
    assert "\n### Fake" not in body
    assert "\\[approve\\]" in body
    assert "https://evil" not in body and "o/r#1" not in body and "www.evil" not in body
    assert "Recommendation: block merge." in body
    assert "x" * 301 not in body


def _fake_gh(tmp_path, comments):
    """A gh that logs its calls and answers the comment listing through the real --jq filter."""
    (tmp_path / "comments.json").write_text(json.dumps(comments))
    gh = tmp_path / "bin" / "gh"
    gh.parent.mkdir()
    gh.write_text(f'''#!/usr/bin/env bash
echo "$*" >> {tmp_path}/gh.log
if [ "$1 $2" = "api --paginate" ]; then jq -r "${{@: -1}}" {tmp_path}/comments.json; fi
''')
    gh.chmod(0o755)


def _run_sh(tmp_path, **env):
    script = _SCRIPT_PATH.parent / "run.sh"
    env = {"PATH": f"{tmp_path / 'bin'}:{os.environ['PATH']}", "GITHUB_ACTION_PATH": str(script.parent.parent),
           "GITHUB_REPOSITORY": "o/r", "RUNNER_TEMP": str(tmp_path / "rt"), "GITHUB_RUN_ID": "7",
           "GITHUB_RUN_ATTEMPT": "1", "PR_NUMBER": "5", **env}
    rc = subprocess.run(["bash", str(script)], env=env, check=False).returncode
    log = tmp_path / "gh.log"
    return rc, log.read_text().splitlines() if log.exists() else []


def test_run_sh_creates_then_edits_the_oldest_bot_comment(tmp_path):
    _verdicts(tmp_path / "rt", TLS)
    (tmp_path / "rt" / "verdicts").rename(tmp_path / "rt" / "flake0-verdicts")
    marker = "<!-- flake0-summary run=7 attempt=1 -->"
    # a person's paste, and a bot comment of another run, are left alone
    _fake_gh(tmp_path, [{"id": 1, "user": {"type": "User"}, "body": marker},
                        {"id": 2, "user": {"type": "Bot"}, "body": "<!-- flake0-summary run=6 attempt=1 -->"},
                        {"id": 3, "user": {"type": "Bot"}, "body": f"quoted {marker}"}])
    rc, calls = _run_sh(tmp_path)
    assert rc == 0
    assert calls[1].startswith("api -X POST repos/o/r/issues/5/comments -F body=@")
    assert len(calls) == 2

    (tmp_path / "gh.log").unlink()
    (tmp_path / "comments.json").write_text(json.dumps([
        {"id": 4, "user": {"type": "Bot"}, "body": f"{marker}\nold"},
        {"id": 5, "user": {"type": "Bot"}, "body": f"{marker}\nduplicate"},
    ]))
    rc, calls = _run_sh(tmp_path, MODE="final")
    assert rc == 0
    assert calls[1].startswith("api -X PATCH repos/o/r/issues/comments/4 -F body=@")
    assert calls[2] == "api -X DELETE repos/o/r/issues/comments/5"


def test_run_sh_skips_outside_pull_requests_and_without_verdicts(tmp_path):
    _fake_gh(tmp_path, [])
    (tmp_path / "rt").mkdir()
    assert _run_sh(tmp_path, PR_NUMBER="") == (0, [])
    assert _run_sh(tmp_path) == (0, [])
